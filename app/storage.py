"""Tiny JSON-on-disk helpers shared by the cast library and slideshows.

We deliberately keep persistence dead simple (JSON files + image files under
data/) so there's no database to set up. Everything is local to the machine.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any


def read_json(path: Path, default: Any) -> Any:
    if not path.exists():
        return default
    with path.open("r", encoding="utf-8") as fh:
        return json.load(fh)


def write_json(path: Path, data: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    with tmp.open("w", encoding="utf-8") as fh:
        json.dump(data, fh, indent=2, ensure_ascii=False)
    tmp.replace(path)  # atomic-ish: avoid corrupting the file on crash
